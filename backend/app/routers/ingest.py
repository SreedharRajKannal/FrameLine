# ---------------------------------------------------------------------------

@router.post("/webhooks/meetily")
async def receive_webhook(request: Request, background_tasks: BackgroundTasks):
    """
    Receive a signed Meetily webhook event.

    1. Verify HMAC signature using MEETILY_WEBHOOK_SECRET
    2. Dedupe by event_id
    3. Return 200 quickly
    4. Process in background task
    """
    # Read raw body for signature verification
    body = await request.body()

    # Get signature headers
    signature = request.headers.get("X-Meetily-Signature", "")
    timestamp = request.headers.get("X-Meetily-Timestamp", "")

    # Verify signature
    if not _verify_signature(config.MEETILY_WEBHOOK_SECRET, timestamp, body, signature):
        raise HTTPException(status_code=401, detail="Invalid webhook signature")

    # Parse event
    import json
    try:
        event = json.loads(body)
    except json.JSONDecodeError:
        raise HTTPException(status_code=400, detail="Invalid JSON body")

    # Dedupe by event_id
    event_id = event.get("event_id", "")
    if not event_id:
        raise HTTPException(status_code=400, detail="Missing event_id")

    if _is_duplicate(event_id):
        return {"status": "duplicate", "event_id": event_id}

    # Mark as processed immediately (before background task)
    _mark_processed(event_id)

    # Track last event
    _last_event_received.update({
        "event_id": event_id,
        "event": event.get("event", ""),
        "received_at": time.time(),
    })

    # Process in background
    event_type = event.get("event", "")
    if event_type == "summary.completed":
        background_tasks.add_task(handle_summary_completed, event)

    return {"status": "accepted", "event_id": event_id}


