# ---------------------------------------------------------------------------
# Processed-events dedup table (same DB as DB_PATH)
# ---------------------------------------------------------------------------

@contextmanager
def _get_conn() -> Generator[sqlite3.Connection, None, None]:
    conn = sqlite3.connect(config.DB_PATH)
    conn.execute("PRAGMA journal_mode=WAL")
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _init_processed_events() -> None:
    """Create processed_events table if not exists."""
    with _get_conn() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS processed_events (
                event_id TEXT PRIMARY KEY,
                received_at REAL NOT NULL
            )
        """)


def _is_duplicate(event_id: str) -> bool:
    """Check if an event_id has already been processed."""
    with _get_conn() as conn:
        row = conn.execute(
            "SELECT 1 FROM processed_events WHERE event_id = ?", (event_id,)
        ).fetchone()
        return row is not None


def _mark_processed(event_id: str) -> None:
    """Mark an event_id as processed."""
    with _get_conn() as conn:
        conn.execute(
            "INSERT OR IGNORE INTO processed_events (event_id, received_at) VALUES (?, ?)",
            (event_id, time.time()),
        )


# Initialize the table on import
_init_processed_events()

# Track last event received (for status endpoint)
_last_event_received: dict = {}


# ---------------------------------------------------------------------------
# Webhook signature verification
# ---------------------------------------------------------------------------

def _verify_signature(secret: str, timestamp: str, body: bytes, header_sig: str) -> bool:
    """
    Verify the Meetily webhook HMAC signature.

    Signature is computed over: {timestamp}.{body}
    Header format: sha256=<hex HMAC-SHA256>
    """
    if not secret or not timestamp or not header_sig:
        return False
    mac = hmac.new(
        secret.encode(),
        timestamp.encode() + b"." + body,
        hashlib.sha256,
    ).hexdigest()
    expected = f"sha256={mac}"
    return hmac.compare_digest(expected, header_sig)


